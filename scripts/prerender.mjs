// Inject route-specific metadata into the built index.html template
function injectRoute(template, route) {
  const fullUrl = `${SITE_URL}${route.path === "/" ? "/" : route.path}`;
  const escTitle = escapeHtml(route.title);
  const escDesc = escapeHtml(route.description);
  const escKw = route.keywords ? escapeHtml(route.keywords) : "";

  let html = template;

  // robots (noindex for private routes)
  if (route.noindex) {
    html = html.replace(
      /<meta\s+name=["']robots["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta name="robots" content="noindex, nofollow" />`,
    );
    html = html.replace(
      /<meta\s+name=["']googlebot["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta name="googlebot" content="noindex, nofollow" />`,
    );
  }

  // <title>
  html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${escTitle}</title>`);
  // meta description
  html = html.replace(
    /<meta\s+name=["']description["']\s+content=["'][^"']*["']\s*\/?>/i,
    `<meta name="description" content="${escDesc}" />`,
  );
  // canonical
  html = html.replace(
    /<link\s+rel=["']canonical["']\s+href=["'][^"']*["']\s*\/?>/i,
    `<link rel="canonical" href="${fullUrl}" />`,
  );
  // og:title
  html = html.replace(
    /<meta\s+property=["']og:title["']\s+content=["'][^"']*["']\s*\/?>/i,
    `<meta property="og:title" content="${escTitle}" />`,
  );
  // og:description
  html = html.replace(
    /<meta\s+property=["']og:description["']\s+content=["'][^"']*["']\s*\/?>/i,
    `<meta property="og:description" content="${escDesc}" />`,
  );
  // og:url
  html = html.replace(
    /<meta\s+property=["']og:url["']\s+content=["'][^"']*["']\s*\/?>/i,
    `<meta property="og:url" content="${fullUrl}" />`,
  );
  // twitter:title
  html = html.replace(
    /<meta\s+name=["']twitter:title["']\s+content=["'][^"']*["']\s*\/?>/i,
    `<meta name="twitter:title" content="${escTitle}" />`,
  );
  // twitter:description
  html = html.replace(
    /<meta\s+name=["']twitter:description["']\s+content=["'][^"']*["']\s*\/?>/i,
    `<meta name="twitter:description" content="${escDesc}" />`,
  );

  // Social preview image. Link-preview bots (WhatsApp, Telegram, Facebook) never
  // run JavaScript, so react-helmet's og:image never reaches them — only this does.
  if (route.image) {
    // A blog post may carry a fully-qualified image URL; site routes use a path.
    const img = escapeHtml(
      /^https?:\/\//i.test(route.image) ? route.image : `${SITE_URL}${route.image}`,
    );
    const imgAlt = escapeHtml(route.imageAlt || route.title);
    const w = String(route.imageWidth || 1200);
    const h = String(route.imageHeight || 630);
    html = html.replace(
      /<meta\s+property=["']og:image["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta property="og:image" content="${img}" />`,
    );
    html = html.replace(
      /<meta\s+property=["']og:image:secure_url["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta property="og:image:secure_url" content="${img}" />`,
    );
    html = html.replace(
      /<meta\s+property=["']og:image:width["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta property="og:image:width" content="${w}" />`,
    );
    html = html.replace(
      /<meta\s+property=["']og:image:height["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta property="og:image:height" content="${h}" />`,
    );
    html = html.replace(
      /<meta\s+property=["']og:image:alt["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta property="og:image:alt" content="${imgAlt}" />`,
    );
    html = html.replace(
      /<meta\s+name=["']twitter:image["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta name="twitter:image" content="${img}" />`,
    );
    html = html.replace(
      /<meta\s+name=["']twitter:image:alt["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta name="twitter:image:alt" content="${imgAlt}" />`,
    );
  }
  // keywords (only for routes that specify)
  if (escKw) {
    html = html.replace(
      /<meta\s+name=["']keywords["']\s+content=["'][^"']*["']\s*\/?>/i,
      `<meta name="keywords" content="${escKw}" />`,
    );
  }
  // itemprop name / description
  html = html.replace(
    /<meta\s+itemprop=["']name["']\s+content=["'][^"']*["']\s*\/?>/i,
    `<meta itemprop="name" content="${escTitle}" />`,
  );
  html = html.replace(
    /<meta\s+itemprop=["']description["']\s+content=["'][^"']*["']\s*\/?>/i,
    `<meta itemprop="description" content="${escDesc}" />`,
  );

  // Route-specific JSON-LD (structured data visible without JavaScript).
  //
  // Marked data-rh so react-helmet-async treats these as its own: when the page
  // mounts, Helmet removes them and writes the component's version. Without the
  // marker both copies stayed, and every page that declared FAQPage in both
  // places rendered two of them — the duplicate Search Console reports.
  // The site-wide graph in index.html carries no marker and is left alone.
  if (route.jsonLd && route.jsonLd.length) {
    const blocks = route.jsonLd
      .map((obj) => `<script type="application/ld+json" data-rh="true">${JSON.stringify(obj)}</script>`)
      .join("\n    ");
    html = html.replace("</head>", `  ${blocks}\n  </head>`);
  }

  // Replace the crawler fallback inside #root with the route-specific one.
  // The attributes may be spread over several lines, so match the opening tag
  // by its id rather than by exact spacing; the block itself contains no nested
  // <div>, so the first `</div></div>` pair closes it and then #root.
  const fallback = buildFallback(route);
  const fallbackPattern = /<div\s[^>]*id="seo-fallback"[\s\S]*?<\/div>\s*<\/div>/;
  if (!fallbackPattern.test(html)) {
    throw new Error(
      `[prerender] Could not find the #seo-fallback block for ${route.path}. ` +
        "index.html changed shape — every route would otherwise ship the home page's fallback content.",
    );
  }
  html = html.replace(fallbackPattern, `${fallback}\n    </div>`);

  return html;
}

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

/**
 * Blog posts live in Supabase, not in this file, so they have to be pulled in at
 * build time. Without this every /blog/<slug> URL is a hard 404: no static file
 * exists and the SPA fallback never gets a chance to run.
 *
 * A failure here must never break the build - it just means no post pages this
 * time round, and the deploy is still good.
 */
/**
 * Vite loads .env itself, but this script runs as plain Node and would not see
 * it - so a build could silently skip the blog posts. Read it here so every
 * environment agrees on what gets prerendered.
 */
async function loadDotEnv() {
  try {
    const raw = await readFile(path.resolve(__dirname, "..", ".env"), "utf8");
    for (const line of raw.split("\n")) {
      const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/i.exec(line);
      if (!match) continue;
      const [, key, rawValue] = match;
      // Real environment variables always win over the checked-in file.
      if (process.env[key]) continue;
      process.env[key] = rawValue.replace(/^["']|["']$/g, "");
    }
  } catch {
    // No .env is normal on CI, where the variables are already set.
  }
}

async function fetchBlogRoutes() {
  await loadDotEnv();
  const base = process.env.VITE_SUPABASE_URL;
  const key = process.env.VITE_SUPABASE_PUBLISHABLE_KEY;
  if (!base || !key) {
    console.warn("[prerender] Supabase env missing - skipping blog post pages.");
    return [];
  }

  let posts;
  try {
    const url =
      `${base}/rest/v1/blog_posts` +
      `?select=slug,title,excerpt,meta_title,meta_description,category,featured_image,created_at,updated_at` +
      `&published=eq.true&order=created_at.desc`;
    const res = await fetch(url, {
      headers: { apikey: key, Authorization: `Bearer ${key}` },
      signal: AbortSignal.timeout(15000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    posts = await res.json();
  } catch (err) {
    console.warn(`[prerender] Could not load blog posts (${err.message}) - skipping.`);
    return [];
  }

  if (!Array.isArray(posts) || posts.length === 0) return [];

  return posts
    .filter((post) => post && typeof post.slug === "string" && post.slug)
    .map((post) => {
      const url = `${SITE_URL}/blog/${post.slug}`;
      const published = post.created_at || undefined;
      const modified = post.updated_at || post.created_at || undefined;
      const description =
        post.meta_description || post.excerpt || `${post.title} - מדריך מאת FilterPhone.`;
      // A post may carry its own image; otherwise the site card is a safe default.
      const image = post.featured_image?.startsWith("http")
        ? post.featured_image
        : post.featured_image || "/hero.jpg";

      return {
        path: `/blog/${post.slug}`,
        title: post.meta_title || `${post.title} | מדריכי FilterPhone`,
        description,
        keywords: [post.category, "סינון טלפון", "מדריך סינון", "FilterPhone"]
          .filter(Boolean)
          .join(", "),
        h1: post.title,
        lead: post.excerpt || description,
        image,
        imageAlt: post.title,
        links: [
          { href: "/blog", text: "כל המדריכים" },
          { href: "/services", text: "שירותי סינון טלפונים באשדוד" },
          { href: "/pricing", text: "מחירון סינון" },
        ],
        jsonLd: [
          {
            "@context": "https://schema.org",
            "@type": "Article",
            headline: post.title,
            description,
            inLanguage: "he",
            mainEntityOfPage: { "@type": "WebPage", "@id": url },
            url,
            datePublished: published,
            dateModified: modified,
            author: { "@type": "Organization", name: "FilterPhone", url: SITE_URL },
            publisher: { "@id": `${SITE_URL}/#business` },
                image: image.startsWith("http") ? image : `${SITE_URL}${image}`,
          },
          {
            "@context": "https://schema.org",
            "@type": "BreadcrumbList",
            itemListElement: [
              { "@type": "ListItem", position: 1, name: "בית", item: `${SITE_URL}/` },
              { "@type": "ListItem", position: 2, name: "מדריכים", item: `${SITE_URL}/blog` },
              { "@type": "ListItem", position: 3, name: post.title, item: url },
            ],
          },
        ],
        lastmod: (modified || published || "").slice(0, 10) || undefined,
      };
    });
}

/**
 * The sitemap used to be a hand-maintained file in public/. It drifted: its
 * lastmod dates froze in the past and it never listed the blog posts at all.
 * Generating it here keeps it in step with whatever was actually prerendered.
 */
const SITEMAP_PRIORITY = {
  "/": "1.0",
  "/services": "0.95",
  "/pricing": "0.9",
  "/filtertube": "0.9",
  "/filterphone": "0.9",
  "/install": "0.85",
  "/compare": "0.85",
  "/contact": "0.8",
  "/about": "0.7",
  "/blog": "0.7",
  "/privacy": "0.3",
  "/refund-policy": "0.3",
};

function sitemapEntry(route, fallbackDate) {
  const loc = `${SITE_URL}${route.path === "/" ? "/" : route.path}`;
  const priority =
    SITEMAP_PRIORITY[route.path] ?? (route.path.startsWith("/blog/") ? "0.6" : "0.8");
  const changefreq = route.path.startsWith("/blog/") ? "monthly" : "weekly";
  return [
    "  <url>",
    `    <loc>${escapeHtml(loc)}</loc>`,
    `    <lastmod>${route.lastmod || fallbackDate}</lastmod>`,
    `    <changefreq>${changefreq}</changefreq>`,
    `    <priority>${priority}</priority>`,
    "  </url>",
  ].join("\n");
}

